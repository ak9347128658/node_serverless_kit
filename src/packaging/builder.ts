/**
 * Build the deployment artifact.
 *
 * 1. Generate an entry module that installs the bundle manifest, maps every
 *    handler reference to a lazy `import()` of the user's module, and appends
 *    the provider's glue code (`Provider.entryCode`).
 * 2. Bundle it with esbuild - TypeScript and JavaScript (ESM or CommonJS)
 *    alike - into a single file in the provider's module format. Each
 *    handler module is only evaluated when its function is first invoked.
 * 3. Copy `package.include` assets and provider files, install `external`
 *    and provider npm dependencies into `node_modules` (for Linux).
 * 4. Write a deterministic `artifact.zip` (sorted entries, fixed timestamps):
 *    an unchanged project never triggers a redeploy.
 *
 * Artifact root layout:
 *
 *     index.js (or the provider's entry file) + .map   bundled code
 *     nskit_manifest.json                              functions, routes, embedded workflows
 *     <provider files>                                 e.g. host.json, package.json
 *     <package.include assets>
 *     node_modules/                                    externals only
 */

import { createHash } from "node:crypto";
import { spawnSync } from "node:child_process";
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import type { BuildOptions, Metafile, Plugin } from "esbuild";
import { importSpecifier, publicApiSource, runtimeSource } from "../core/paths.js";
import { locateHandler, type Project } from "../core/project.js";
import { ORCHESTRATOR_HANDLER, type Artifact, type Provider } from "../providers/base.js";
import type { BundleManifest } from "../runtime/manifest.js";
import { collectFiles } from "./glob.js";
import { createZip, type ZipEntry } from "./zip.js";

export class BuildError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "BuildError";
  }
}

export type Log = (message: string) => void;

export interface BuildArtifactOptions {
  /** Skip `npm install` of externals (faster `nskit package` for review). */
  skipInstall?: boolean;
  log?: Log;
}

export interface EntryOptions {
  /** Directory the entry module is written to. */
  entryDir: string;
  manifest: BundleManifest;
  /** Glue code appended after the handler table. */
  glue: string;
}

const RUNTIME_MODULE_PREFIX = "node-serverless-kit/";

function writeText(file: string, text: string): void {
  mkdirSync(path.dirname(file), { recursive: true });
  writeFileSync(file, text.replace(/\r\n/g, "\n"), "utf-8");
}

/** Generate the entry module source. Exported for tests. */
export function entrySource(project: Project, options: EntryOptions): string {
  const { entryDir, manifest, glue } = options;
  const source = project.sourceDir;
  const lines = [
    "// Generated by node-serverless-kit. Do not edit - regenerate with `nskit package`.",
    `import { installBundle } from ${JSON.stringify(importSpecifier(entryDir, runtimeSource("manifest")))};`,
    `import manifest from "./nskit_manifest.json";`,
    "",
    "const pick = (mod, path) => path.reduce((value, key) => (value == null ? value : value[key]), mod);",
    "const handlers = {",
  ];
  const refs = [...new Set(Object.values(manifest.functions).map((f) => f.handler))].sort();
  for (const ref of refs) {
    let specifier: string;
    let exportPath: string[];
    if (ref === ORCHESTRATOR_HANDLER) {
      specifier = importSpecifier(entryDir, runtimeSource("workflow"));
      exportPath = ["orchestrate"];
    } else if (ref.startsWith(RUNTIME_MODULE_PREFIX)) {
      throw new BuildError(`unknown built-in handler '${ref}'`);
    } else {
      const located = locateHandler(source, ref);
      if (!located) throw new BuildError(`handler '${ref}': module not found under ${source}`);
      specifier = importSpecifier(entryDir, located.file);
      exportPath = located.exportPath;
    }
    lines.push(
      `  ${JSON.stringify(ref)}: () => import(${JSON.stringify(specifier)}).then((m) => pick(m, ${JSON.stringify(exportPath)})),`,
    );
  }
  lines.push("};", "", "installBundle({ manifest, handlers });", "", glue.trim(), "");
  return lines.join("\n");
}

function resolveTsconfig(project: Project): string | undefined {
  const configured = project.config.package.tsconfig;
  if (configured) {
    const file = path.resolve(project.root, configured);
    if (!existsSync(file)) throw new BuildError(`package.tsconfig ${file} does not exist`);
    return file;
  }
  const fallback = path.join(project.root, "tsconfig.json");
  return existsSync(fallback) ? fallback : undefined;
}

export interface BundleResult {
  outFile: string;
  metafile?: Metafile;
  warnings: string[];
}

/** Bundle the entry module with esbuild. */
export async function bundleEntry(
  project: Project,
  entryFile: string,
  outFile: string,
  target: Provider["bundle"],
  esbuildTarget: string,
): Promise<BundleResult> {
  const esbuild = await import("esbuild");
  const pkg = project.config.package;
  const options: BuildOptions = {
    entryPoints: [entryFile],
    outfile: outFile,
    bundle: true,
    format: target.format,
    platform: target.platform,
    target: target.platform === "node" ? esbuildTarget : "es2022",
    conditions: target.conditions,
    sourcemap: pkg.sourcemap ? "linked" : false,
    sourcesContent: false,
    minify: pkg.minify,
    keepNames: true,
    legalComments: "none",
    charset: "utf8",
    absWorkingDir: project.root,
    tsconfig: resolveTsconfig(project),
    external: [...(target.external ?? []), ...pkg.external],
    logLevel: "silent",
    metafile: true,
    define: { "process.env.NODE_ENV": '"production"' },
    banner:
      target.platform === "node" && target.format === "esm"
        ? { js: "import { createRequire as __nskitCreateRequire } from 'node:module'; const require = __nskitCreateRequire(import.meta.url);" }
        : undefined,
    ...(target.esbuild ?? {}),
    ...(pkg.esbuild as BuildOptions),
  };
  // `node-serverless-kit` in user code -> the same runtime sources the entry uses, so
  // handlers and the dispatcher share one copy. Only the bare name: subpaths resolve normally.
  const aliasPlugin: Plugin = {
    name: "nskit-runtime-alias",
    setup(build) {
      build.onResolve({ filter: /^node-serverless-kit$/ }, () => ({ path: publicApiSource() }));
    },
  };
  options.plugins = [aliasPlugin, ...(options.plugins ?? [])];
  try {
    const result = await esbuild.build(options);
    return {
      outFile,
      metafile: result.metafile,
      warnings: result.warnings.map((w) => `${w.location ? `${w.location.file}:${w.location.line}: ` : ""}${w.text}`),
    };
  } catch (err) {
    const failure = err as { errors?: { text: string; location?: { file: string; line: number; column: number } }[] };
    if (failure.errors?.length) {
      const details = failure.errors
        .slice(0, 20)
        .map((e) => `  ${e.location ? `${e.location.file}:${e.location.line}:${e.location.column}: ` : ""}${e.text}`)
        .join("\n");
      throw new BuildError(
        `bundling failed:\n${details}\nHint: packages that cannot be bundled (native addons) belong in \`package.external\`.`,
      );
    }
    throw err;
  }
}

/** Exact versions of `names` from the project's installed node_modules (falls back to package.json ranges). */
function pinnedVersions(root: string, names: string[]): Record<string, string> {
  const out: Record<string, string> = {};
  let declared: Record<string, string> = {};
  const pkgFile = path.join(root, "package.json");
  if (existsSync(pkgFile)) {
    const pkg = JSON.parse(readFileSync(pkgFile, "utf-8"));
    declared = { ...(pkg.devDependencies ?? {}), ...(pkg.optionalDependencies ?? {}), ...(pkg.dependencies ?? {}) };
  }
  for (const name of names) {
    if (name.includes("*")) continue; // wildcard externals (e.g. "@aws-sdk/*") are provided by the platform
    const installed = path.join(root, "node_modules", name, "package.json");
    if (existsSync(installed)) out[name] = JSON.parse(readFileSync(installed, "utf-8")).version;
    else out[name] = declared[name] ?? "*";
  }
  return out;
}

function sortedObject(obj: Record<string, string>): Record<string, string> {
  return Object.fromEntries(Object.entries(obj).sort(([a], [b]) => (a < b ? -1 : 1)));
}

function npmInstall(buildDir: string, architecture: string, log: Log): void {
  const npm = process.platform === "win32" ? "npm.cmd" : "npm";
  const args = [
    "install",
    "--omit=dev",
    "--no-audit",
    "--no-fund",
    "--no-package-lock",
    "--loglevel=error",
    "--os=linux",
    `--cpu=${architecture === "arm64" ? "arm64" : "x64"}`,
    "--libc=glibc",
  ];
  log(`  npm ${args.join(" ")}`);
  const proc = spawnSync(npm, args, { cwd: buildDir, encoding: "utf-8", shell: process.platform === "win32" });
  if (proc.status !== 0) {
    throw new BuildError(
      `npm install failed while installing external dependencies:\n${(proc.stderr || proc.stdout || String(proc.error ?? "")).slice(-4000)}\n` +
        "Hint: a native dependency may have no prebuilt Linux binary; build the artifact on Linux (e.g. in CI or Docker).",
    );
  }
}

function listFiles(dir: string, prefix = ""): string[] {
  const out: string[] = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const rel = prefix + entry.name;
    if (entry.isDirectory()) out.push(...listFiles(path.join(dir, entry.name), rel + "/"));
    else if (entry.isFile()) out.push(rel);
  }
  return out;
}

export function zipDirectory(dir: string, zipPath: string): number {
  const entries: ZipEntry[] = listFiles(dir).map((rel) => {
    const full = path.join(dir, rel);
    const executable = process.platform !== "win32" && (statSync(full).mode & 0o111) !== 0 && /(^|\/)[^.]+$|\.sh$/.test(rel);
    return { name: rel, data: readFileSync(full), executable };
  });
  writeFileSync(zipPath, createZip(entries));
  return entries.length;
}

export function digest(file: string): { hex: string; base64: string } {
  const h = createHash("sha256").update(readFileSync(file));
  const raw = h.digest();
  return { hex: raw.toString("hex"), base64: raw.toString("base64") };
}

export async function buildArtifact(project: Project, options: BuildArtifactOptions = {}): Promise<Artifact> {
  const log = options.log ?? (() => undefined);
  const { config, provider, workDir } = project;
  const buildDir = path.join(workDir, "build");
  const entryDir = path.join(workDir, "entry");
  rmSync(buildDir, { recursive: true, force: true });
  rmSync(entryDir, { recursive: true, force: true });
  mkdirSync(buildDir, { recursive: true });
  mkdirSync(entryDir, { recursive: true });

  // 1. entry module
  const manifest = project.bundleManifest();
  const manifestJson = JSON.stringify(manifest, null, 2) + "\n";
  writeText(path.join(entryDir, "nskit_manifest.json"), manifestJson);
  const glue = provider.entryCode({
    config,
    manifest,
    runtime: (module) => importSpecifier(entryDir, runtimeSource(module)),
  });
  const entryFile = path.join(entryDir, "nskit-entry.ts");
  writeText(entryFile, entrySource(project, { entryDir, manifest, glue }));

  // 2. bundle
  const target = provider.bundleTarget(config);
  const outFile = path.join(buildDir, target.entryFile);
  const bundled = await bundleEntry(project, entryFile, outFile, target, provider.esbuildTarget(config.provider.runtime));
  for (const w of bundled.warnings) log(`  esbuild warning: ${w}`);
  const inputs = Object.keys(bundled.metafile?.inputs ?? {}).filter((f) => !f.includes("node-serverless-kit") && !f.includes(".nskit"));
  log(`  bundled ${inputs.length} module(s) -> ${target.entryFile} (${target.format}/${target.platform})`);

  // 3. assets, manifest, provider files, dependencies
  const source = project.sourceDir;
  const assets = collectFiles(source, config.package.include, config.package.exclude);
  for (const file of assets) {
    const dest = path.join(buildDir, path.relative(source, file));
    mkdirSync(path.dirname(dest), { recursive: true });
    cpSync(file, dest);
  }
  if (assets.length) log(`  copied ${assets.length} asset file(s) from package.include`);
  writeText(path.join(buildDir, "nskit_manifest.json"), manifestJson);
  const extra = provider.extraFiles(config, manifest);
  for (const [rel, content] of Object.entries(extra)) writeText(path.join(buildDir, rel), content);

  const externalNames = config.package.external.filter((n) => !n.includes("*"));
  const deps = sortedObject({ ...provider.dependencies, ...pinnedVersions(project.root, externalNames) });
  // Node decides CJS vs ESM from the nearest package.json; pin it so the bundle
  // loads the same way in the cloud and locally inside a `"type": "module"` project.
  if (target.platform === "node" || Object.keys(deps).length || "package.json" in extra) {
    const pkgPath = path.join(buildDir, "package.json");
    const base = existsSync(pkgPath) ? JSON.parse(readFileSync(pkgPath, "utf-8")) : {};
    const pkgJson: Record<string, unknown> = {
      name: `${config.service}-${config.provider.stage}`,
      version: "1.0.0",
      private: true,
      ...(target.platform === "node" ? { type: target.format === "esm" ? "module" : "commonjs" } : {}),
      ...base,
    };
    const allDeps = sortedObject({ ...(base.dependencies ?? {}), ...deps });
    if (Object.keys(allDeps).length) pkgJson.dependencies = allDeps;
    writeText(pkgPath, JSON.stringify(pkgJson, null, 2) + "\n");
    if (Object.keys(deps).length && !provider.remoteInstall) {
      if (options.skipInstall) log(`  skipped installing ${Object.keys(deps).length} dependency(ies) (--skip-install)`);
      else {
        log(`  installing ${Object.keys(deps).length} dependency(ies) for linux/${config.provider.architecture}`);
        npmInstall(buildDir, config.provider.architecture, log);
      }
    }
  }

  // 4. zip
  const zipPath = path.join(workDir, "artifact.zip");
  const count = zipDirectory(buildDir, zipPath);
  const { hex, base64 } = digest(zipPath);
  const size = statSync(zipPath).size;
  log(`  artifact artifact.zip: ${count} files, ${(size / 1024).toFixed(1)} KiB, sha256 ${hex.slice(0, 12)}`);
  return { path: zipPath, sha256: hex, sha256Base64: base64, size, fileCount: count, buildDir, entryFile: target.entryFile };
}
