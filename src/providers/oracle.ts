/**
 * Oracle Cloud Infrastructure: OCI Functions (container images) + API Gateway + Events.
 *
 * OCI Functions only run container images. nskit writes a `Dockerfile`,
 * `func.yaml` and `func.js` (Fn Project Node FDK glue) into the build directory
 * and either
 *
 * - uses a pre-built image (`options.image`), or
 * - builds and pushes one with your local Docker (`options.image_repository`),
 *   tagged with the artifact hash, from a `terraform_data` resource.
 *
 * `@fnproject/fdk` is installed by `npm install` inside the Docker build (it is
 * listed in the artifact's package.json) and is only required by `func.js`;
 * the bundled runtime never imports it.
 *
 * Options (`provider.options`): `compartment_id`, `subnet_ids` (required),
 * `image` | `image_repository`, `gateway_subnet_id`, `gateway_endpoint_type`
 * (PUBLIC | PRIVATE), and provider auth: `config_file_profile`, `auth`,
 * `tenancy_ocid`, `user_ocid`, `fingerprint`, `private_key_path`.
 * Per-function `options` are merged into `oci_functions_function`.
 */

import { corsOf, eventsOf, type ServiceConfig } from "../config/schema.js";
import type { BundleManifest } from "../runtime/manifest.js";
import {
  HTTP,
  Issue,
  Provider,
  STORAGE,
  type BundleTarget,
  type Capability,
  type EntryContext,
  type RenderContext,
} from "./base.js";
import { escape, escapeMap, ref, tfId, type TerraformDoc } from "./terraform-doc.js";

const FUNCTION = "oci_functions_function";
/** Fn Project Node FDK, installed into the image (never bundled). */
export const FDK_PACKAGE = "@fnproject/fdk";
export const FDK_VERSION = "0.0.112";
const EVENT_TYPES: Record<"created" | "deleted", string[]> = {
  created: ["com.oraclecloud.objectstorage.createobject", "com.oraclecloud.objectstorage.updateobject"],
  deleted: ["com.oraclecloud.objectstorage.deleteobject"],
};

/** `/files/{path+}` -> `/files/{path*}` (OCI's greedy wildcard). */
export function ociPath(path: string): string {
  return path.replace(/\+\}/g, "*}");
}

export class OracleProvider extends Provider {
  readonly name = "oracle";
  readonly displayName = "Oracle Cloud Functions";
  override readonly tier = "experimental";
  readonly terraformSource = "oracle/oci";
  override readonly terraformVersion = ">= 6.0";
  override readonly terraformLocalName = "oci";
  override readonly defaultRegion = "us-ashburn-1";
  override readonly capabilities = new Set<Capability>([HTTP, STORAGE]);
  override readonly maxNameLength = 100;
  /** Canonical runtime -> `fnproject/node:<tag>` image tag. */
  override readonly runtimes = { nodejs20: "20", nodejs22: "22", nodejs24: "24" };
  override readonly maxTimeout = 300;
  override readonly notes =
    "Functions run as container images built from the Fn Node FDK: set options.image (pre-built) or " +
    "options.image_repository (nskit runs docker build/push). Needs options.compartment_id and options.subnet_ids. " +
    "HTTP via API Gateway, object-storage triggers via Events rules. No schedule/queue/topic triggers. You must add IAM " +
    "policies letting API Gateway and Events invoke functions.";
  override readonly bundle: BundleTarget = { format: "cjs", platform: "node", entryFile: "index.js", external: [FDK_PACKAGE] };
  override readonly dependencies = { [FDK_PACKAGE]: FDK_VERSION };
  /** Dependencies are installed by `npm install` inside the Docker build (on Linux). */
  override readonly remoteInstall = true;

  // ------------------------------------------------------------------ bundle
  entryCode(ctx: EntryContext): string {
    return `export { handler } from ${JSON.stringify(ctx.runtime("adapters/oracle"))};`;
  }

  override extraFiles(config: ServiceConfig, _manifest: BundleManifest): Record<string, string> {
    const tag = (this.runtimes as Record<string, string>)[config.provider.runtime] ?? "22";
    return {
      "func.js":
        "// Generated by node-serverless-kit. Fn FDK entrypoint: node func.js\n" +
        '"use strict";\n' +
        `const fdk = require(${JSON.stringify(FDK_PACKAGE)});\n` +
        'const { handler } = require("./index.js");\n' +
        '\nfdk.handle((input, ctx) => handler(input, ctx, fdk.rawResult), { inputMode: "buffer" });\n',
      "func.yaml":
        "schema_version: 20180708\n" +
        `name: ${config.service}\n` +
        "version: 0.0.1\n" +
        "runtime: node\n" +
        `build_image: fnproject/node:${tag}-dev\n` +
        `run_image: fnproject/node:${tag}\n` +
        "entrypoint: node func.js\n" +
        `memory: ${config.provider.memory}\n`,
      Dockerfile:
        "# Generated by node-serverless-kit\n" +
        `FROM fnproject/node:${tag}-dev AS build-stage\n` +
        "WORKDIR /function\n" +
        "COPY package.json /function/\n" +
        "RUN npm install --omit=dev --no-audit --no-fund --no-package-lock\n" +
        `FROM fnproject/node:${tag}\n` +
        "WORKDIR /function\n" +
        "COPY . /function/\n" +
        "COPY --from=build-stage /function/node_modules/ /function/node_modules/\n" +
        'ENTRYPOINT ["node", "func.js"]\n',
      ".dockerignore": "node_modules\n",
    };
  }

  override providerBlock(ctx: RenderContext): Record<string, unknown> {
    const block: Record<string, unknown> = { region: ctx.region };
    for (const key of ["config_file_profile", "auth", "tenancy_ocid", "user_ocid", "fingerprint", "private_key_path"]) {
      if (ctx.opt(key)) block[key] = ctx.opt(key);
    }
    return block;
  }

  override extraValidation(config: ServiceConfig): Issue[] {
    const opts = config.provider.options;
    const issues: Issue[] = [];
    if (!opts.compartment_id) issues.push(new Issue("error", "options.compartment_id is required", "provider.options"));
    if (!Array.isArray(opts.subnet_ids) || !opts.subnet_ids.length) {
      issues.push(new Issue("error", "options.subnet_ids (list of subnet OCIDs) is required", "provider.options"));
    }
    if (!opts.image && !opts.image_repository) {
      issues.push(
        new Issue(
          "error",
          "OCI Functions need a container image. Either set options.image_repository " +
            "(e.g. iad.ocir.io/<namespace>/<repo>) and nskit runs `docker build` + `docker push` for you, " +
            "or build it yourself and set options.image:\n" +
            "    docker login <region-key>.ocir.io\n" +
            "    docker build -t <image> .nskit/oracle-<stage>/build\n" +
            "    docker push <image>",
          "provider.options.image",
        ),
      );
    }
    let hasHttp = false;
    for (const [name, fn] of Object.entries(config.functions)) {
      for (const ev of eventsOf(fn, "http")) {
        hasHttp = true;
        if (ev.auth !== "none") {
          issues.push(
            new Issue(
              "error",
              `auth \`${ev.auth}\` is not wired up for OCI API Gateway yet; add an authentication policy via ` +
                "provider.terraform.extra or validate tokens in the handler",
              `functions.${name}`,
            ),
          );
        }
      }
      for (const ev of eventsOf(fn, "storage")) {
        if (ev.prefix || ev.suffix) {
          issues.push(new Issue("warning", "OCI Events rules cannot filter by prefix/suffix; filter in the handler", `functions.${name}`));
        }
        if (ev.existing) {
          issues.push(new Issue("warning", `bucket ${ev.bucket} must have 'Emit Object Events' enabled`, `functions.${name}`));
        }
      }
    }
    if (hasHttp) {
      issues.push(
        new Issue(
          "warning",
          "API Gateway needs an IAM policy to call functions, e.g. `ALLOW any-user to use functions-family " +
            "in compartment <name> where ALL {request.principal.type = 'ApiGateway'}`",
          "provider",
        ),
      );
    }
    return issues;
  }

  // ------------------------------------------------------------------ render
  private image(doc: TerraformDoc, ctx: RenderContext): [string, string[]] {
    const prebuilt = ctx.opt<string | undefined>("image");
    if (prebuilt) return [escape(String(prebuilt)), []];
    const repo = String(ctx.opt("image_repository", "")).replace(/\/+$/, "");
    const image = `${repo}:${ctx.artifact.sha256.slice(0, 16)}`;
    const platform = ctx.config.provider.architecture === "arm64" ? "linux/arm64" : "linux/amd64";
    const build = doc.resource("terraform_data", "image", {
      triggers_replace: [escape(image)],
      provisioner: [
        {
          "local-exec": {
            working_dir: "${path.module}",
            command: escape(`docker build --platform ${platform} -t ${image} build && docker push ${image}`),
          },
        },
      ],
    });
    return [escape(image), [build]];
  }

  renderResources(doc: TerraformDoc, ctx: RenderContext): void {
    const cfg = ctx.config;
    const compartment = escape(String(ctx.opt("compartment_id", "")));
    const subnets = (ctx.opt<unknown[]>("subnet_ids", []) ?? []).map((s) => escape(String(s)));
    const [image, depends] = this.image(doc, ctx);
    const app = doc.resource("oci_functions_application", "app", {
      compartment_id: compartment,
      display_name: ctx.prefix,
      subnet_ids: subnets,
      shape: cfg.provider.architecture === "arm64" ? "GENERIC_ARM" : "GENERIC_X86",
      freeform_tags: ctx.tags(),
    });
    const fns: Record<string, string> = {};
    for (const [name, fn] of ctx.functionItems()) {
      const body: Record<string, unknown> = {
        application_id: ref(app, "id"),
        display_name: ctx.physicalName(name),
        // The top-level `image` argument is deprecated in favour of source_details (oracle/oci >= 6.x).
        source_details: { source_type: "CONTAINER_IMAGE", image },
        memory_in_mbs: String(ctx.memoryOf(fn)),
        timeout_in_seconds: ctx.timeoutOf(fn),
        config: escapeMap(ctx.environment(name, fn)),
        freeform_tags: ctx.tags(fn),
      };
      if (depends.length) body.depends_on = depends;
      Object.assign(body, fn.options);
      fns[name] = doc.resource(FUNCTION, name, body);
    }

    const deployment = this.http(doc, ctx, compartment, subnets, fns);
    this.storage(doc, ctx, compartment, fns);

    const fnOut: Record<string, Record<string, unknown>> = {};
    for (const [name, fn] of ctx.functionItems()) {
      const out: Record<string, unknown> = {
        id: ref(fns[name], "id"),
        console: `https://cloud.oracle.com/functions/apps/${ref(app, "id")}/fn/${ref(fns[name], "id")}?region=${ctx.region}`,
      };
      if (deployment && eventsOf(fn, "http").length) out.base_url = ref(deployment, "endpoint");
      fnOut[name] = out;
    }
    const wfOut: Record<string, unknown> = {};
    for (const n of Object.keys(cfg.workflows).sort()) wfOut[n] = { id: ref(FUNCTION, tfId(`${n}-orchestrator`), "id") };
    doc.output(
      "nskit",
      { functions: fnOut, workflows: wfOut, endpoint: deployment ? ref(deployment, "endpoint") : null },
      { description: "node-serverless-kit deployment summary" },
    );
  }

  private http(
    doc: TerraformDoc,
    ctx: RenderContext,
    compartment: string,
    subnets: string[],
    fns: Record<string, string>,
  ): string | undefined {
    const routes: Record<string, unknown>[] = [];
    for (const [name, fn] of ctx.functionItems()) {
      for (const ev of eventsOf(fn, "http")) {
        const methods = [ev.method];
        if (corsOf(ev) && ev.method !== "ANY" && ev.method !== "OPTIONS") methods.push("OPTIONS");
        routes.push({
          path: ociPath(ev.path),
          methods,
          backend: { type: "ORACLE_FUNCTIONS_BACKEND", function_id: ref(fns[name], "id") },
        });
      }
    }
    if (!routes.length) return undefined;
    const gatewaySubnet = ctx.opt<string | undefined>("gateway_subnet_id");
    const gw = doc.resource("oci_apigateway_gateway", "gateway", {
      compartment_id: compartment,
      display_name: ctx.prefix,
      endpoint_type: String(ctx.opt("gateway_endpoint_type", "PUBLIC")),
      subnet_id: gatewaySubnet ? escape(String(gatewaySubnet)) : (subnets[0] ?? ""),
      freeform_tags: ctx.tags(),
    });
    return doc.resource("oci_apigateway_deployment", "http", {
      compartment_id: compartment,
      gateway_id: ref(gw, "id"),
      display_name: ctx.prefix,
      path_prefix: `/${ctx.service}`,
      specification: { routes },
      freeform_tags: ctx.tags(),
    });
  }

  private storage(doc: TerraformDoc, ctx: RenderContext, compartment: string, fns: Record<string, string>): void {
    for (const [name, fn] of ctx.functionItems()) {
      for (const ev of eventsOf(fn, "storage")) {
        const label = `b-${ev.bucket}`;
        if (!ev.existing && !doc.hasResource("oci_objectstorage_bucket", label)) {
          const ns = doc.data("oci_objectstorage_namespace", "ns", { compartment_id: compartment });
          doc.resource("oci_objectstorage_bucket", label, {
            compartment_id: compartment,
            name: ev.bucket,
            namespace: ref(ns, "namespace"),
            object_events_enabled: true,
            freeform_tags: ctx.tags(),
          });
        }
        const types = ev.events.flatMap((e) => EVENT_TYPES[e]);
        const condition = { eventType: types, data: { additionalDetails: { bucketName: ev.bucket } } };
        const body: Record<string, unknown> = {
          compartment_id: compartment,
          display_name: ctx.physicalName(`${name}-${ev.bucket}`),
          is_enabled: true,
          condition: escape(JSON.stringify(condition)),
          actions: { actions: [{ action_type: "FAAS", is_enabled: true, function_id: ref(fns[name], "id") }] },
          freeform_tags: ctx.tags(),
        };
        if (!ev.existing) body.depends_on = [`oci_objectstorage_bucket.${tfId(label)}`];
        doc.resource("oci_events_rule", `${name}-${ev.bucket}`, body);
      }
    }
  }
}
